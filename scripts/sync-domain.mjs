import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(path.join(root, 'shared/structure-plan.js'), 'utf8');
const content = '// Generated by npm run sync:domain; edit shared/structure-plan.js instead.\n' + source;
for (const target of ['cloudfunctions/engineer-api/structure-plan.js', 'cloudfunctions/generation-worker/structure-plan.js', 'miniprogram/lib/structure-plan.js']) {
  fs.mkdirSync(path.dirname(path.join(root, target)), { recursive: true });
  fs.writeFileSync(path.join(root, target), content);
}
console.log('Synchronized structure-plan domain rules for independent WeChat deployment packages.');
