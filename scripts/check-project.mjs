import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mini = path.join(root, 'miniprogram');
const files = directory => fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? files(path.join(directory, entry.name)) : [path.join(directory, entry.name)]);
const all = files(mini);
const app = JSON.parse(fs.readFileSync(path.join(mini, 'app.json'), 'utf8'));
const project = JSON.parse(fs.readFileSync(path.join(root, 'project.config.json'), 'utf8'));
const domainSource = '// Generated by npm run sync:domain; edit shared/structure-plan.js instead.\n' + fs.readFileSync(path.join(root, 'shared/structure-plan.js'), 'utf8');
for (const target of ['cloudfunctions/engineer-api/structure-plan.js', 'cloudfunctions/generation-worker/structure-plan.js', 'miniprogram/lib/structure-plan.js']) assert.equal(fs.readFileSync(path.join(root, target), 'utf8'), domainSource, 'Run npm run sync:domain: ' + target);
const catalogue = JSON.parse(fs.readFileSync(path.join(mini, 'data/catalogue.json'), 'utf8'));
assert.ok(fs.readFileSync(path.join(mini, 'data/catalogue.ts'), 'utf8').includes(JSON.stringify(catalogue, null, 2)), 'Run npm run build:content after editing the catalogue');
for (const file of files(path.join(root, 'cloudbase')).filter(file => file.endsWith('.json') && !file.includes(path.sep + 'seed' + path.sep))) JSON.parse(fs.readFileSync(file, 'utf8'));
for (const file of files(path.join(root, 'cloudbase/seed'))) {
  for (const line of fs.readFileSync(file, 'utf8').trim().split('\n')) assert.ok(JSON.parse(line)._id, 'Seed document requires _id: ' + file);
}
assert.equal(project.appid, 'wx4d0fe4f65e530325');
assert.equal(project.miniprogramRoot, 'miniprogram/');
const routes = new Set([...app.pages, ...app.subPackages.flatMap(pkg => pkg.pages.map(page => pkg.root + '/' + page))]);
for (const route of routes) for (const extension of ['.ts', '.json', '.wxml', '.wxss']) assert.ok(fs.existsSync(path.join(mini, route + extension)), 'Missing page: ' + route + extension);
for (const tab of app.tabBar.list) assert.ok(app.pages.includes(tab.pagePath), 'Tab must live in main package');
for (const file of all.filter(file => file.endsWith('.json'))) {
  const config = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const component of Object.values(config.usingComponents || {})) {
    if (component.startsWith('/')) assert.ok(fs.existsSync(path.join(mini, component + '.json')), 'Missing component: ' + component);
  }
}
for (const file of all.filter(file => file.endsWith('.wxml'))) {
  assert.ok(!fs.readFileSync(file, 'utf8').includes('&amp;&amp;'), 'WXML expressions must use raw &&: ' + file);
}
for (const file of all.filter(file => file.endsWith('.ts'))) {
  assert.ok(!/(?:require\s*\(|from\s*)['"][^'"]+\.json['"]/.test(fs.readFileSync(file, 'utf8')), 'Native mini-program modules cannot import JSON: ' + file);
}
for (const file of files(path.join(root, 'cloudfunctions')).filter(file => file.endsWith('.js'))) {
  const result = spawnSync(process.execPath, ['--check', file], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
}
const bytes = all.filter(file => !file.includes(path.sep + 'package-engineer' + path.sep)).reduce((sum, file) => sum + fs.statSync(file).size, 0);
assert.ok(bytes < 2 * 1024 * 1024, 'Main package source exceeds 2 MiB');
console.log('PASS: JSON, routes, components, cloud function syntax; main-package source ' + (bytes / 1024 / 1024).toFixed(2) + ' MiB.');
const binRoot = path.join(process.env.WECHAT_DEVTOOLS_PATH || '/Applications/wechatwebdevtools.app', 'Contents/Resources/app.asar.unpacked/node_modules/wcc-exec');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'xinxin-compile-'));
try {
  for (const [extension, binary] of [['.wxml', 'wcc'], ['.wxss', 'wcsc']]) {
    const executable = path.join(binRoot, binary);
    if (!fs.existsSync(executable)) { console.log('SKIP: ' + binary + ' unavailable; verify in WeChat DevTools.'); continue; }
    let count = 0;
    for (const file of all.filter(file => file.endsWith(extension))) {
      const result = spawnSync(executable, ['-o', path.join(temporary, String(count++) + '.js'), path.relative(mini, file)], { cwd: mini, encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 });
      assert.equal(result.status, 0, file + '\n' + result.stderr + '\n' + result.stdout);
    }
    console.log('PASS: native WeChat ' + binary + ' compiled ' + count + ' files.');
  }
} finally { fs.rmSync(temporary, { recursive: true }); }
