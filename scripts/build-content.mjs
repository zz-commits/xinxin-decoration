import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogue = JSON.parse(fs.readFileSync(path.join(root, 'miniprogram/data/catalogue.json'), 'utf8'));
// The mini-program loader only loads script modules, not arbitrary JSON files.
fs.writeFileSync(path.join(root, 'miniprogram/data/catalogue.ts'), '// Generated by npm run build:content; edit catalogue.json instead.\nimport type { Catalogue } from \'../models/content\';\nexport const catalogue: Catalogue = ' + JSON.stringify(catalogue, null, 2) + ';\n');
const seedDir = path.join(root, 'cloudbase/seed');
fs.mkdirSync(seedDir, { recursive: true });
fs.writeFileSync(path.join(seedDir, 'store_config.jsonl'), JSON.stringify({ ...catalogue.store, status: 'published' }) + '\n');
fs.writeFileSync(path.join(seedDir, 'services.jsonl'), catalogue.services.map(item => JSON.stringify({ ...item, status: 'published' })).join('\n') + '\n');
fs.writeFileSync(path.join(seedDir, 'generation_locks.jsonl'), JSON.stringify({ _id: 'image-worker', runId: '', lockedUntil: '' }) + '\n');
// DevTools import accepts .json, but expects one JSON document per line.
const consoleDir = path.join(seedDir, 'console');
fs.mkdirSync(consoleDir, { recursive: true });
for (const name of ['store_config', 'services', 'generation_locks']) fs.copyFileSync(path.join(seedDir, name + '.jsonl'), path.join(consoleDir, name + '.json'));
console.log('Generated the native catalogue module and CloudBase seed files.');
